package com.gamq.deportes.model;

import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.experimental.Accessors;
import org.hibernate.annotations.SQLDelete;
import org.hibernate.annotations.Where;

import javax.persistence.*;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/** Dated enrollment of an independent student in one school. */
@Getter @Setter @NoArgsConstructor
@EqualsAndHashCode(callSuper = false)
@Accessors(chain = true)
@Entity
@Table(name = "inscripciones_escuela")
@SQLDelete(sql = "UPDATE inscripciones_escuela SET estado=true WHERE id_inscripcion=?")
@Where(clause = "estado = false")
public class EstudianteEscuela {
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id_inscripcion")
    private Long idEstudiante;
    @Column(name = "uuid", updatable = false, unique = true, nullable = false, length = 50)
    private String uuid;
    @Column(name = "estado", nullable = false)
    private boolean estado;
    @Column(name = "fecha_creacion", nullable = false, updatable = false)
    private LocalDateTime fechaCreacion;
    @Column(name = "fecha_actualizacion", nullable = false)
    private LocalDateTime fechaActualizacion;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "id_estudiante", nullable = false)
    private Estudiante estudiante;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "id_organizacion", nullable = false)
    private Organizacion organizacionDto;

    // Responsible only for this enrollment; null means the school manages it.
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "id_responsable")
    private Contribuyente contribuyenteDto;

    @Column(name = "fecha_inscripcion", nullable = false)
    private LocalDate fechaInscripcion;
    @Column(name = "fecha_baja")
    private LocalDate fechaBaja;
    @Column(name = "motivo_baja", length = 500)
    private String motivoBaja;
    // Generated by the PostgreSQL trigger in the migration.
    @Column(name = "matricula", unique = true, length = 50, insertable = false)
    private String matricula;
    @Column(name = "activo", nullable = false)
    private Boolean activo = true;

    @OneToMany(mappedBy = "estudianteEscuela", fetch = FetchType.LAZY)
    private List<ReservaPeriodo> mensualidadesDtoList = new ArrayList<>();

    public EstudianteEscuela(String uuid) { this.uuid = uuid; }

    @PrePersist
    public void prePersist() {
        if (uuid == null) uuid = UUID.randomUUID().toString();
        if (fechaCreacion == null) fechaCreacion = LocalDateTime.now();
        if (fechaActualizacion == null) fechaActualizacion = LocalDateTime.now();
        if (activo == null) activo = true;
        if (fechaInscripcion == null) fechaInscripcion = LocalDate.now();
    }
    @PreUpdate public void preUpdate() { fechaActualizacion = LocalDateTime.now(); }
    public boolean estaActivo() { return !estado && Boolean.TRUE.equals(activo) && fechaBaja == null; }
    public void darDeBaja() { activo = false; fechaBaja = LocalDate.now(); }
    public void reactivar() { activo = true; fechaBaja = null; motivoBaja = null; }
}
